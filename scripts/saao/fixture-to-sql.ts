const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const qn = (s: string | null) => (s === null ? "null" : q(s));
const nn = (n: number | null) => (n === null ? "null" : String(n));

/** Integer centavos to an exact peso decimal literal (string ops only). */
export function pesos(c: number): string {
  const abs = Math.abs(c);
  const s = String(Math.floor(abs / 100)) + "." + String(abs % 100).padStart(2, "0");
  return c < 0 ? `-${s}` : s;
}
function uid(prefix: string, i: number): string {
  return `${prefix}-0000-0000-0000-${String(i + 1).padStart(12, "0")}`;
}

function row(a: Amounts): string {
  const sb = `${q(JSON.stringify(Object.fromEntries(Object.entries(a.sb).map(([k, v]) => [k, Number(pesos(v))]))))}::jsonb`;
  // JSON numbers via Number() are only used for 2-decimal pesos; jsonb stores them as exact numerics.
  return [
    pesos(a.appropriation), pesos(a.nta), sb, pesos(a.supplemental), pesos(a.realignment), pesos(a.totalChanges),
    pesos(a.adjusted), pesos(a.allotment), pesos(a.obligation),
    `array[${a.months.map(pesos).join(", ")}]::numeric[]`,
    pesos(a.balanceAppropriation), pesos(a.balanceAllotment), pesos(a.cna1), pesos(a.cna2), pesos(a.cna3),
    pesos(a.savings), pesos(a.savingsHalf),
  ].map((v, i) => (i === 2 || i === 9 ? v : `${v}::numeric`)).join(", ");
}

const COLS = "appropriation, nta, sb, supplemental, realignment, total_changes, adjusted, allotment, obligation, months, balance_appropriation, balance_allotment, cna_1, cna_2, cna_3, savings, savings_half";

